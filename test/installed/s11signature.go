// The names of S11 signature-mismatch do not end in "secret": the evidence
// redactor takes "secret: x" and "secret=x" for a credential and blanks x,
// and the summary's problems name a scenario as "S11/<variant>: <result>".
const (
	s11SignatureLane                = "lab-installed-ha-s11-signature-mismatch"
	s11SignatureVariant             = "signature-mismatch"
	s11SignatureRecordFile          = "S11/signature-mismatch/record.json"
	s11SignatureSourceDataCheckFile = "S11/signature-mismatch/source-data-check.json"
	s11SignatureBackupName          = "s11-signature-mismatch"
	// s11SignatureClusterName is the standalone cluster whose
	// spec.objectStorage names s11SignatureSecretName, the Secret with the
	// seed Secret's access key and a wrong secret key.
	s11SignatureClusterName = "s11-signature"
	s11SignatureSecretName  = "object-storage-signature"
	// signatureDoesNotMatch is the S3 error code of a request signed with
	// another secret key than the one the store holds for its access key.
	signatureDoesNotMatch = "SignatureDoesNotMatch"
)

// signatureFault is S11 signature-mismatch: the seed Secret's access key,
// which the object store knows, with a random secret key. The access key is
// already registered with the redactor and searched for as a seed key.
func (h *haRun) signatureFault() s11KeyFault {
	return s11KeyFault{variant: s11SignatureVariant, recordFile: s11SignatureRecordFile,
		sourceDataCheckFile: s11SignatureSourceDataCheckFile, backup: s11SignatureBackupName,
		cluster: s11SignatureClusterName, secret: s11SignatureSecretName, keys: "the mismatched keys",
		code: signatureDoesNotMatch, readyLimit: h.cfg.BackupSignatureMismatchReadyLimit,
		makeKeys: func(h *haRun) (string, string) { return h.accessKey, rand.Text() + rand.Text() },
		keyNote: "the mismatched keys are the seed Secret's access key with a wrong secret key, random and " +
			"generated by the run; neither is recorded; with them the run only lists the backup bucket under the " +
			"prefix, and with the seed Secret's keys it lists the same at the end; it never writes to or removes " +
			"from the object store",
		refusalNote: "a pass needs the object store to answer the run's own client with the S3 error code " +
			signatureDoesNotMatch + " before anything is created, and its answer quoted in the failure " +
			"(storeError) to refuse the keys (storeErrorKind access-denied); another answer blocks the variant"}
}

// validateS11Signature checks the inputs of S11 signature-mismatch, when it
// is selected; BackupBucket is checked by validateS11.
func (c HAConfig) validateS11Signature() error {
	if !c.BackupSignatureMismatch {
		return nil
	}
	for _, other := range []struct {
		selected bool
		flag     string
	}{{c.Restore, "-restore"}, {c.BackupMissingDestination, "-backup-missing-destination"},
		{c.BackupDeniedCredentials, "-backup-denied-credentials"},
		{c.BackupInterruptedUpload, "-backup-interrupted-upload"}} {
		if other.selected {
			return fmt.Errorf("-backup-signature-mismatch and %s select different lanes; a run takes one of them",
				other.flag)
		}
	}
	if c.BackupSignatureMismatchReadyLimit <= 0 {
		return errors.New("-backup-signature-mismatch needs a positive -backup-signature-mismatch-ready-limit " +
			"for its cluster")
	}
	return nil
}

// planS11SignatureMismatch returns the lane and the requirements of a run
// that selects S11 signature-mismatch after S11 complete, and names it in the
// summary's first note; otherwise lane and requirements as they are.
func planS11SignatureMismatch(cfg HAConfig, lane string, requirements []evidence.Requirement,
	summary *evidence.Summary) (string, []evidence.Requirement) {
	if !cfg.BackupSignatureMismatch {
		return lane, requirements
	}
	summary.Notes[0] = "Three-member HA cluster against an installed Operator, then S11 complete and S11 " +
		"signature-mismatch: a full backup to object storage, downloaded and checked by the run, and a backup of " +
		"a standalone cluster whose object store Secret holds the seed Secret's access key with a wrong secret " +
		"key, which must end Failed; no other S00-S15 qualification"
	return s11SignatureLane, append(requirements, evidence.Requirement{ID: s11ID, Variant: s11SignatureVariant})
}

// runS11SignatureMismatch runs S11 signature-mismatch after S11 complete
// passed, with the seed Secret's access key and a random secret key
// (runS11KeyFault). The run's own client must be refused with
// SignatureDoesNotMatch.
func (h *haRun) runS11SignatureMismatch(ctx context.Context) evidence.Scenario {
	return h.runS11KeyFault(ctx, h.signatureFault())
}
